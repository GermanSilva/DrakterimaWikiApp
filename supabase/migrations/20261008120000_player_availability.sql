-- H9b1: availability belongs to the PLAYER (auth user), not to a character or a campaign.
--
--   * New table `player_availability` (personal windows + whole-day "not available" marks).
--       campaign_id NULL  = general: applies to every campaign the user takes part in.
--       campaign_id SET   = pinned to that one campaign (the user must be a member of it).
--   * `disponibilidad` keeps ONLY session slots (tipo = 'sesion'): DM writes, members read.
--     Existing personal / no_disponible rows are moved to player_availability through the
--     character's owner (rows whose character has no owner, or whose owner is no longer a member
--     of that campaign, are dropped: there is nobody to attribute them to). Moved rows stay PINNED
--     to the campaign they were created in, so a legacy entry never silently starts applying to
--     the owner's other campaigns.
--   * `campaign_busy_slots(campaign)` tells a campaign's members which of its participants are
--     already booked by a session slot of ANOTHER campaign, without naming that campaign.
--
-- Visibility of player_availability (SELECT):
--   own rows                                           -> always
--   general row (campaign_id is null)                  -> users that share at least one campaign with the owner
--   pinned row  (campaign_id = X)                      -> members of X, provided the owner is (still) a member of X
-- Write (insert / update / delete): own rows only; a row that is pinned (insert, update) must point
-- at a campaign the caller belongs to. DMs are ordinary users here: they manage their own rows.
--
-- Client contract:
--   * user_id is never client-writable (no insert/update privilege): it is filled by the default
--     auth.uid() and cannot be reassigned.
--   * Realtime: the table is published. A `campaign_id=eq.<id>` filter cannot match general rows
--     (campaign_id is NULL), so clients subscribe WITHOUT a filter and rely on RLS; DELETE events
--     carry only the primary key (default replica identity) and are not RLS-filtered, exactly like
--     the other published tables (ids only, no content).

------------------------------------------------------------------------------
-- player_availability
------------------------------------------------------------------------------

create table public.player_availability (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  campaign_id  uuid references public.campaigns (id) on delete cascade,
  tipo         text not null check (tipo in ('personal', 'no_disponible')),
  fecha        date,
  fecha_inicio date,
  fecha_fin    date,
  hora_inicio  time,
  hora_fin     time,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  check (tipo <> 'no_disponible' or fecha is not null),
  check (tipo = 'no_disponible'
         or (fecha_inicio is not null and fecha_fin is not null
             and hora_inicio is not null and hora_fin is not null
             and fecha_fin >= fecha_inicio))
);
create index player_availability_user_id_idx on public.player_availability (user_id);
create index player_availability_campaign_id_idx on public.player_availability (campaign_id)
  where campaign_id is not null;

comment on table public.player_availability is
  'Per-player availability. campaign_id NULL = general (every campaign the user is in); set = pinned to that campaign.';

create trigger player_availability_set_updated_at
  before update on public.player_availability
  for each row execute function public.set_updated_at();

alter table public.player_availability enable row level security;

-- True when the CALLER and `uid` are both members of `cid`. Answers false for every other
-- combination, so it cannot be used to probe the membership of campaigns the caller is not in.
create function public.campaign_has_member(cid uuid, uid uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.campaign_members me
    join public.campaign_members them on them.campaign_id = me.campaign_id
    where me.campaign_id = cid
      and me.user_id = (select auth.uid())
      and them.user_id = uid
  );
$$;

revoke execute on function public.campaign_has_member(uuid, uuid) from public, anon, authenticated;
grant execute on function public.campaign_has_member(uuid, uuid) to authenticated;

create policy player_availability_select on public.player_availability
  for select to authenticated
  using (
    user_id = (select auth.uid())
    or (campaign_id is null and public.shares_campaign_with(user_id))
    or (campaign_id is not null and public.campaign_has_member(campaign_id, user_id))
  );

create policy player_availability_insert on public.player_availability
  for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and (campaign_id is null or public.is_campaign_member(campaign_id))
  );

create policy player_availability_update on public.player_availability
  for update to authenticated
  using (user_id = (select auth.uid()))
  with check (
    user_id = (select auth.uid())
    and (campaign_id is null or public.is_campaign_member(campaign_id))
  );

create policy player_availability_delete on public.player_availability
  for delete to authenticated
  using (user_id = (select auth.uid()));

revoke all on public.player_availability from anon, authenticated;
grant select, delete on public.player_availability to authenticated;
grant insert (campaign_id, tipo, fecha, fecha_inicio, fecha_fin, hora_inicio, hora_fin)
  on public.player_availability to authenticated;
grant update (campaign_id, tipo, fecha, fecha_inicio, fecha_fin, hora_inicio, hora_fin)
  on public.player_availability to authenticated;

------------------------------------------------------------------------------
-- Move existing personal / no_disponible rows, then restrict disponibilidad to sessions
------------------------------------------------------------------------------

insert into public.player_availability
  (user_id, campaign_id, tipo, fecha, fecha_inicio, fecha_fin, hora_inicio, hora_fin, created_at)
select distinct on (p.owner_id, d.campaign_id, d.tipo, d.fecha, d.fecha_inicio, d.fecha_fin, d.hora_inicio, d.hora_fin)
  p.owner_id, d.campaign_id, d.tipo, d.fecha, d.fecha_inicio, d.fecha_fin, d.hora_inicio, d.hora_fin, d.created_at
from public.disponibilidad d
join public.pjs p
  on p.id = d.character_id and p.campaign_id = d.campaign_id
join public.campaign_members m
  on m.campaign_id = d.campaign_id and m.user_id = p.owner_id
where d.tipo in ('personal', 'no_disponible')
  and p.owner_id is not null
order by p.owner_id, d.campaign_id, d.tipo, d.fecha, d.fecha_inicio, d.fecha_fin, d.hora_inicio, d.hora_fin, d.created_at;

delete from public.disponibilidad where tipo <> 'sesion';

-- The old policies reference character_id, so they go before the column does.
drop policy disponibilidad_select on public.disponibilidad;
drop policy disponibilidad_insert on public.disponibilidad;
drop policy disponibilidad_update on public.disponibilidad;
drop policy disponibilidad_delete on public.disponibilidad;

-- Dropping the columns also drops the character FK, its index and the CHECKs that mention them.
alter table public.disponibilidad drop column character_id;
alter table public.disponibilidad drop column fecha;

alter table public.disponibilidad drop constraint if exists disponibilidad_tipo_check;
alter table public.disponibilidad add constraint disponibilidad_sesion_only check (tipo = 'sesion');

create policy disponibilidad_select on public.disponibilidad
  for select to authenticated
  using (public.is_campaign_member(campaign_id));

create policy disponibilidad_insert on public.disponibilidad
  for insert to authenticated
  with check (public.is_campaign_dm(campaign_id));

create policy disponibilidad_update on public.disponibilidad
  for update to authenticated
  using (public.is_campaign_dm(campaign_id))
  with check (public.is_campaign_dm(campaign_id));

create policy disponibilidad_delete on public.disponibilidad
  for delete to authenticated
  using (public.is_campaign_dm(campaign_id));

------------------------------------------------------------------------------
-- campaign_busy_slots: other campaigns' session slots, per participant, anonymised
------------------------------------------------------------------------------
-- For every member of p_campaign_id that ALSO belongs to another campaign, returns that other
-- campaign's session slots as (user_id, dates, times). Nothing that identifies the other campaign
-- (id, name, slug, slot id, title, role) is returned; identical slots of several campaigns collapse
-- into one row. Only members of p_campaign_id may call it (42501 otherwise).
-- Disclosure: a member learns that a co-member is booked at some time. That is the approved product
-- behaviour ("busy" without naming the other campaign).

create function public.campaign_busy_slots(p_campaign_id uuid)
returns table (user_id uuid, fecha_inicio date, fecha_fin date, hora_inicio time, hora_fin time)
language plpgsql
stable
security definer
set search_path = ''
as $$
#variable_conflict use_column
begin
  if not public.is_campaign_member(p_campaign_id) then
    raise exception 'not_a_member' using errcode = '42501';
  end if;

  return query
  select distinct this_m.user_id, d.fecha_inicio, d.fecha_fin, d.hora_inicio, d.hora_fin
  from public.campaign_members this_m
  join public.campaign_members other_m
    on other_m.user_id = this_m.user_id
   and other_m.campaign_id <> p_campaign_id
  join public.disponibilidad d
    on d.campaign_id = other_m.campaign_id
   and d.tipo = 'sesion'
  where this_m.campaign_id = p_campaign_id
  order by 2, 4, 1, 3, 5;
end;
$$;

revoke execute on function public.campaign_busy_slots(uuid) from public, anon, authenticated;
grant execute on function public.campaign_busy_slots(uuid) to authenticated;

